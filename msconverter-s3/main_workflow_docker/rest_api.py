# Extraction of Metadata from mzml files

@app.route("/extract/mzml_metadata/json", methods=["POST"])
@app.input(FileMetadata, location='form_and_files')
@app.doc(tags=['FileMetadata:MetadataExtraction'])
def mzml_metadata_extraction(form_and_files_data):
    uploaded_file = form_and_files_data["main_file"]
    if not uploaded_file.filename:
        return jsonify(error="empty filename"), 400

    file_id = foldername()
    filename = secure_filename(uploaded_file.filename)
    metadata_parameter = form_and_files_data["include_parameter"]

    if not filename.lower().endswith('.mzml'):
        return jsonify({'error': 'File is not of mzML extention'}), 400

    print("Incoming Files: \n")
    
    try:
        upload_fileobj(uploaded_file, filename, file_id)
    except ClientError as e:
        return jsonify({'Error Type': str(e)}) , 500

    try:
        download_url = download_file(filename=filename, file_id=file_id)
    except (ClientError,BotoCoreError) as e:
        return jsonify({'Error Type': str(e)}) , 500 
    
    try:
        output_folder_path = os.path.join(working_dir, file_id)
        new_path = fetch_file(url=download_url, filename=filename, folder_id=file_id)
        output_file_name = filename.rsplit(".", 1)[0] + "_metadata.json"
        output_file_path = os.path.join(output_folder_path, output_file_name)

        # label -> kwargs
        META_OPTS = {
            "none":                       {},
            "with spectra":               {"include_spectra": True},
            "with chromatogram":          {"include_chromatograms": True},
            "with spectra+chromatogram":  {"include_spectra": True, "include_chromatograms": True},
        }

        metadata = extract_metadata(new_path, **META_OPTS[metadata_parameter])

        with open(output_file_path, "w", encoding="utf-8") as f:
            for chunk in json.JSONEncoder(indent=2, ensure_ascii=False).iterencode(metadata):
                f.write(chunk) 
        
        with open(output_file_path,'rb') as fh:
            upload_fileobj(fh, output_file_name, file_id)
        download_url = download_file(filename=output_file_name, file_id=file_id)

        remove_folder(output_folder_path)

        payload = {
                "status": "success",
                "process": "Metadata Extraction",
                "file_info": {
                    "filename": output_file_name,
                    "download_url": download_url,
                    "valid_for": "1 hour"
                },
                "meta": {
                    "message": "Metadata Extraction in mzml Schema",
                    "timestamp": datetime.datetime.now(pytz.timezone("Europe/Berlin")).isoformat(),
                    "http_status": 200
                }
            }
        
        return Response(
                json.dumps(payload, indent=2, ensure_ascii=False),
                mimetype="application/json"
            ), 200

    except Exception as e:
        remove_folder(output_folder_path)
        return jsonify({'error': 'Error during Metadata Extraction', 'details': str(e)}), 500


    

