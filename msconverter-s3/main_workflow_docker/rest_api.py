@app.route("/convert/msconvert", methods=["POST"])
@app.input(Files_convert, location='form_and_files')
#@app.output(MSConvertOut)
@app.doc(tags=['msconvert:Conversion'])
def msfile_conversion(form_and_files_data):
    uploaded_file = form_and_files_data["main_file"]
    if not uploaded_file.filename:
        return jsonify({'Error Type: Empty File Name Found'}) , 400

    file_id = foldername()
    filename = secure_filename(uploaded_file.filename)

    config_parameters = form_and_files_data["parameters"]

    cleanup()
    try:
        upload_fileobj(uploaded_file, filename, file_id)
    except ClientError as e:
        return jsonify({'Error Type': str(e)}) , 500

    try:
        download_url = download_file(filename=filename, file_id=file_id)
    except (ClientError,BotoCoreError) as e:
        return jsonify({'Error Type': str(e)}) , 500
    
    try:
        #if filename.endswith('.tar') or filename.lower().endswith('raw'):
        if filename.lower().endswith(('.tar', '.tar.gz' ,'.tar.xz', '.raw')):
            request1= requests.post(url="http://nfdi4chem-ms-msconvert:4000/msconvert_file",
            json={
                'filename': filename,
                'download_url': download_url,
                'foldername': file_id,
                'config': config_parameters
            })
            request1.raise_for_status()
            print(request1.json())
            mzml_name = request1.json()["mzml_outputfile_name"]
            payload = {
                "status": "success",
                "file_info": {
                    "filename": mzml_name,
                    "download_url": request1.json().get("mzml_download_url"),
                    "valid_for": "1 hour"
                },
                "meta": {
                    "message": f"Converted File - '{mzml_name}' is ready for download.",
                    "timestamp": datetime.datetime.now(pytz.timezone("Europe/Berlin")).isoformat(),
                    "http_status": request1.status_code
                }
            }
            return Response(
                json.dumps(payload, indent=2, ensure_ascii=False),
                mimetype="application/json"
            ), 200
        else:
            return jsonify({"error": "Invalid file type"}), 400   
    except Exception as e:
        return jsonify({'Error_type': str(e)}), 500


    
